// Builds this server's n8n credentials and workflows from the settings in .env.
// install.sh runs it inside the n8n container (it has Node.js): node render.js <in dir> <out dir>
const fs = require('fs');
const [inDir, outDir] = process.argv.slice(2);
const E = process.env;
const fail = msg => { console.error('render: ' + msg); process.exit(1); };

const missing = ['ALERT_EMAIL_TO', 'SMTP_HOST', 'SMTP_USER', 'SMTP_PASSWORD', 'POSTGRES_PASSWORD'].filter(k => !E[k]);
if (missing.length) fail('missing in .env: ' + missing.join(', '));
const ai = E.AI_INVESTIGATION || 'off';
if (!['off', 'local'].includes(ai)) fail('AI_INVESTIGATION must be off or local');
const every = Number(E.SCAN_EVERY_MINUTES || 1);
if (!(every >= 1 && every <= 60)) fail('SCAN_EVERY_MINUTES must be 1 to 60');
const list = s => (s || '').split(',').map(x => x.trim()).filter(Boolean);
const labels = Object.fromEntries(list(E.APP_LABELS).map(pair => {
  const [k, v] = pair.split('=').map(x => (x || '').trim());
  if (!k || !v) fail(`APP_LABELS entry "${pair}" must look like project=name`);
  return [k, v];
}));
const smtpPort = Number(E.SMTP_PORT || 465);
const ollama = E.OLLAMA_URL || 'http://127.0.0.1:11434';

const settings = {
  email_from: E.ALERT_EMAIL_FROM || E.SMTP_USER,
  email_to: E.ALERT_EMAIL_TO,
  ai_investigation: ai,
  timezone: E.TIMEZONE || 'UTC',
  app_labels: labels,
  ignore_apps: list(E.IGNORE_APPS),
};

const credentials = [
  { id: 'aiOpsPostgres01', name: 'AI Ops Postgres', type: 'postgres',
    data: { host: '127.0.0.1', port: 5433, database: 'ops', user: 'ops', password: E.POSTGRES_PASSWORD, ssl: 'disable' } },
  { id: 'aiOpsSmtp01', name: 'AI Ops SMTP', type: 'smtp',
    data: { host: E.SMTP_HOST, port: smtpPort, user: E.SMTP_USER, password: E.SMTP_PASSWORD, secure: smtpPort === 465 } },
  { id: 'aiOpsOllama01', name: 'Local Ollama', type: 'ollamaApi', data: { baseUrl: ollama } },
];

const watch = JSON.parse(fs.readFileSync(`${inDir}/app-watch.json`, 'utf8'));
for (const n of watch.nodes) {
  if (n.name === 'Settings') n.parameters.jsCode = '// Generated by install.sh from .env\nreturn [{ json: ' + JSON.stringify(settings, null, 2) + ' }];';
  if (n.name === 'Every minute') n.parameters.rule.interval[0].minutesInterval = every;
  if (n.name === 'Local model' && E.OLLAMA_MODEL) n.parameters.model = E.OLLAMA_MODEL;
  if (n.credentials && n.credentials.smtp) n.credentials.smtp = { id: 'aiOpsSmtp01', name: 'AI Ops SMTP' };
}
fs.writeFileSync(`${outDir}/app-watch.json`, JSON.stringify(watch));

const triage = fs.readFileSync(`${inDir}/alert-triage.json`, 'utf8').split('http://127.0.0.1:11434').join(ollama);
fs.writeFileSync(`${outDir}/alert-triage.json`, triage);
fs.writeFileSync(`${outDir}/credentials.json`, JSON.stringify(credentials));
console.log(`render: settings ok (report to ${settings.email_to}, scan every ${every} min, AI ${ai}, ${Object.keys(labels).length} app label(s))`);
